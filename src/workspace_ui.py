"""Native Qt workspace panels; no web views, external assets, or network calls."""

from PySide6.QtCore import Qt
from PySide6.QtGui import QColor, QPixmap
from PySide6.QtWidgets import (QFrame, QVBoxLayout, QHBoxLayout, QLabel, QPushButton,
    QLineEdit, QComboBox, QListWidget, QGroupBox, QStackedWidget, QWidget,
    QProgressBar, QSpinBox, QSizePolicy, QScrollArea)

from .annotation_scene import AnnotationScene
from .image_viewer import ImageViewer
from .branding import APP_NAME, LOGO_PATH, ORGANIZATION


def label(text, name="muted"):
    widget = QLabel(text)
    widget.setObjectName(name)
    return widget


def button(text, callback, name="", tip=""):
    widget = QPushButton(text)
    widget.setObjectName(name)
    widget.clicked.connect(callback)
    widget.setToolTip(tip)
    widget.setCursor(Qt.PointingHandCursor)
    return widget


def panel():
    widget = QFrame()
    widget.setObjectName("panel")
    layout = QVBoxLayout(widget)
    layout.setContentsMargins(16, 18, 16, 16)
    layout.setSpacing(12)
    return widget, layout


def header(window):
    widget = QFrame()
    widget.setObjectName("appHeader")
    layout = QHBoxLayout(widget)
    layout.setContentsMargins(24, 17, 24, 17)
    layout.setSpacing(14)
    window.brand_logo = QLabel()
    window.brand_logo.setObjectName("brandLogo")
    window.brand_logo.setFixedSize(168, 54)
    window.brand_logo.setAlignment(Qt.AlignCenter)
    window.brand_logo.setAccessibleName(ORGANIZATION + " logo")
    window.brand_logo.setToolTip(ORGANIZATION)
    ratio = window.devicePixelRatioF()
    logo = QPixmap(str(LOGO_PATH)).scaled(int(168 * ratio), int(54 * ratio), Qt.KeepAspectRatio, Qt.SmoothTransformation)
    logo.setDevicePixelRatio(ratio)
    window.brand_logo.setPixmap(logo)
    layout.addWidget(window.brand_logo)
    titles = QVBoxLayout()
    titles.setSpacing(2)
    title = label(APP_NAME, "appTitle")
    title.setWordWrap(True)
    titles.addWidget(title)
    subtitle = label("A focused workspace for image annotation")
    subtitle.setWordWrap(True)
    titles.addWidget(subtitle)
    layout.addLayout(titles, 1)
    window.save_badge = label("Ready", "saveBadge")
    layout.addWidget(window.save_badge)
    layout.addWidget(button("Open Folder", window.open_folder, tip="Open an image folder (Ctrl+O)"))
    window.save_button = button("Save", window.save_project, tip="Save project now (Ctrl+S)")
    window.export_button = button("Export Labels", window.export_annotations, "primary", "Export VOC, YOLO, and COCO (Ctrl+Shift+E)")
    layout.addWidget(window.save_button)
    layout.addWidget(window.export_button)
    return widget


