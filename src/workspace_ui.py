def canvas_panel(window):
    widget = QFrame()
    widget.setObjectName("workspace")
    layout = QVBoxLayout(widget)
    layout.setContentsMargins(16, 16, 16, 14)
    layout.setSpacing(12)
    top = QHBoxLayout()
    window.image_title = label("Workspace", "sectionTitle")
    window.image_title.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Preferred)
    top.addWidget(window.image_title, 1)
    window.image_meta = label("", "imageMeta")
    top.addWidget(window.image_meta)
    layout.addLayout(top)
    tools = QHBoxLayout()
    group = QFrame()
    group.setObjectName("toolGroup")
    modes = QHBoxLayout(group)
    modes.setContentsMargins(3, 3, 3, 3)
    modes.setSpacing(2)
    for attribute, text, mode, tip in [
        ("select_tool_btn", "Select", "select", "Select, move, and resize boxes (S)"),
        ("box_tool_btn", "Draw Box", "box", "Drag to draw a bounding box (B)"),
        ("pan_tool_btn", "Pan", "pan", "Drag to move around the image (H)")]:
        control = button(text, lambda checked=False, value=mode: window.set_tool(value), "tool", tip)
        control.setCheckable(True)
        control.setChecked(mode == "select")
        setattr(window, attribute, control)
        modes.addWidget(control)
    tools.addWidget(group)
    tools.addStretch()
    tools.addWidget(button("Fit", window.fit_to_window, tip="Fit image in the workspace (Ctrl+0)"))
    tools.addWidget(button("100%", window.zoom_100, tip="View original scale (Ctrl+1)"))
    layout.addLayout(tools)
    window.scene = AnnotationScene(window.project_manager)
    window.viewer = ImageViewer(window.scene)
    window.viewer.setBackgroundBrush(QColor("#eff3f2"))
    window.scene.box_created.connect(window.on_box_created)
    window.scene.annotations_changed.connect(window.schedule_autosave)
    window.scene.box_edited.connect(window.on_box_edited)
    window.scene.selectionChanged.connect(window.update_box_properties)
    window.canvas_stack = QStackedWidget()
    welcome = QWidget()
    empty = QVBoxLayout(welcome)
    empty.setContentsMargins(20, 30, 20, 30)
    empty.addStretch()
    for text, role in [("A CLEAR START", "eyebrow"), ("Start with an image folder", "emptyTitle"),
                       ("Open your images, draw a box, and give it a label.", "muted"),
                       ("Existing VOC annotations are loaded automatically.", "muted")]:
        line = label(text, role)
        line.setAlignment(Qt.AlignCenter)
        line.setWordWrap(True)
        empty.addWidget(line)
    open_button = button("Open Image Folder", window.open_folder, "primary")
    open_button.setMaximumWidth(210)
    empty.addSpacing(12)
    empty.addWidget(open_button, 0, Qt.AlignHCenter)
    empty.addSpacing(22)
    guide = label("01  Open a folder     02  Draw and adjust     03  Export labels")
    guide.setAlignment(Qt.AlignCenter)
    guide.setWordWrap(True)
    empty.addWidget(guide)
    empty.addStretch()
    window.canvas_stack.addWidget(welcome)
    window.canvas_stack.addWidget(window.viewer)
    layout.addWidget(window.canvas_stack, 1)
    window.tool_hint = label("Tip: choose Draw Box or press B, then drag around an object.")
    window.tool_hint.setWordWrap(True)
    layout.addWidget(window.tool_hint)
    navigation = QHBoxLayout()
    window.previous_button = button("Previous", window.previous_image, tip="Previous matching image (Left / A)")
    window.next_button = button("Next", window.next_image, tip="Next matching image (Right / D)")
    navigation.addWidget(window.previous_button)
    window.position_label = label("No image selected")
    navigation.addWidget(window.position_label)
    navigation.addStretch()
    navigation.addWidget(label("Go to"))
    window.image_jump = QSpinBox()
    window.image_jump.setMinimum(1)
    window.image_jump.setMaximum(1)
    window.image_jump.setKeyboardTracking(False)
    window.image_jump.setFixedWidth(84)
    window.image_jump.setAccessibleName("Go to image number")
    window.image_jump.valueChanged.connect(lambda number: window.set_current_image(number-1))
    navigation.addWidget(window.image_jump)
    navigation.addWidget(window.next_button)
    layout.addLayout(navigation)
    return widget


def labels_panel(window):
    widget, layout = panel()
    layout.setSpacing(8)
    widget.setMinimumWidth(215)
    layout.addWidget(label("ANNOTATION", "eyebrow"))
    layout.addWidget(label("Labels", "sectionTitle"))
    window.ai_button = button("AI Assist...", window.open_ai_assist, tip="Generate draft boxes with text-prompted Grounding DINO")
    layout.addWidget(window.ai_button)
    window.ai_review_label = label("", "muted")
    window.ai_review_label.setWordWrap(True)
    layout.addWidget(window.ai_review_label)
    window.ai_review_actions = QWidget()
    review_actions = QHBoxLayout(window.ai_review_actions)
    review_actions.setContentsMargins(0, 0, 0, 0)
    window.approve_ai_button = button("Approve", lambda: window.review_ai_image("approved"), "primary")
    window.reject_ai_button = button("Reject", lambda: window.review_ai_image("rejected"), "danger")
    review_actions.addWidget(window.approve_ai_button)
    review_actions.addWidget(window.reject_ai_button)
    layout.addWidget(window.ai_review_actions)
    hint = label("Double-click a label to apply it.")
    hint.setWordWrap(True)
    layout.addWidget(hint)
    window.class_list = QListWidget()
    window.class_list.setMinimumHeight(60)
    window.class_list.setMaximumHeight(110)
    window.class_list.itemDoubleClicked.connect(window.on_class_double_click)
    window.class_list.setContextMenuPolicy(Qt.CustomContextMenu)
    window.class_list.customContextMenuRequested.connect(window.show_class_context_menu)
    layout.addWidget(window.class_list, 1)
    actions = QHBoxLayout()
    actions.addWidget(button("Add Label", window.add_class))
    actions.addWidget(button("Remove", window.delete_selected_class, "danger", "Remove the selected label"))
    layout.addLayout(actions)
    window.rename_label_button = button("Rename Label...", window.rename_selected_class,
        tip="Rename the selected label across all images; AI-approved boxes will need review again")
    layout.addWidget(window.rename_label_button)
    details = QGroupBox("Box details")
    detail_layout = QVBoxLayout(details)
    detail_layout.setSpacing(10)
    window.box_info_label = label("Select a box to view its coordinates.")
    window.box_info_label.setWordWrap(True)
    detail_layout.addWidget(window.box_info_label)
    detail_layout.addWidget(label("Active label"))
    window.class_combo = QComboBox()
    window.class_combo.setAccessibleName("Active annotation label")
    window.class_combo.currentIndexChanged.connect(window.on_class_changed)
    detail_layout.addWidget(window.class_combo)
    window.delete_box_btn = button("Delete Selected Box", window.delete_selected_boxes, "danger")
    detail_layout.addWidget(window.delete_box_btn)
    layout.addWidget(details)
    help_text = label("Your project autosaves. Export labels when you are ready to use them.")
    help_text.setWordWrap(True)
    layout.addWidget(help_text)
    # Small laptop windows retain usable controls instead of compressing fields.
    widget.setMinimumHeight(550)
    scroll = QScrollArea()
    scroll.setObjectName("labelsScroll")
    scroll.setFrameShape(QFrame.NoFrame)
    scroll.setWidgetResizable(True)
    scroll.setMinimumWidth(235)
    scroll.setWidget(widget)
    return scroll
